// বাংলা অঙ্কে টাইপ করা সংখ্যা (০১৭...) ইংরেজি অঙ্কে রূপান্তর — সার্ভার যাচাই ASCII অঙ্ক চায়
export function toAsciiDigits(s: string) {
  return s.replace(/[০-৯]/g, (d) => String("০১২৩৪৫৬৭৮৯".indexOf(d)));
}

// বাংলাদেশি মোবাইল নম্বর: ০১৩–০১৯ দিয়ে শুরু, মোট ১১ অঙ্ক; +৮৮/৮৮ উপসর্গ বাদ দেওয়া হয়
export function normalizeBdPhone(raw: string) {
  const d = toAsciiDigits(raw).replace(/[\s-]/g, "").replace(/^\+?88/, "");
  return d;
}

export function isValidBdPhone(phone: string) {
  return /^01[3-9]\d{8}$/.test(phone);
}
